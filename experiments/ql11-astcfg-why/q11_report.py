"""Write results/inventory.csv, results/gap_cost.csv and results/summary.md (no model call).

Reads results/*.csv written by q11_struct.py, q11_why.py, q11_compare.py and the committed results
of the earlier experiments. Usage: python -B q11_report.py
"""

from __future__ import annotations

import csv
from collections import defaultdict
from pathlib import Path
from typing import Any

import q11_env as env


def read(p: Path) -> list[dict[str, str]]:
    with p.open(encoding="utf-8", newline="") as fh:
        return list(csv.DictReader(fh))


def write(name: str, rows: list[dict[str, Any]]) -> None:
    with (env.RES / name).open("w", encoding="utf-8", newline="") as fh:
        w = csv.DictWriter(fh, list(rows[0]), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def md(rows: list[dict[str, Any]], cols: list[str] | None = None) -> str:
    cols = cols or list(rows[0])
    out = ["| " + " | ".join(cols) + " |", "| " + " | ".join("---" for _ in cols) + " |"]
    out += ["| " + " | ".join(str(r.get(c, "")) for c in cols) + " |" for r in rows]
    return "\n".join(out) + "\n"


def inventory() -> list[dict[str, Any]]:
    out: list[dict[str, Any]] = []
    srcs = (("llm-pilot (variant re)", env.EXP / "llm-pilot" / "results" / "re" / "results.csv",
             "tier"),
            ("llm-full", env.EXP / "llm-full" / "results" / "results.csv", ""),
            ("llm-hints2", env.EXP / "llm-hints2" / "results" / "results.csv", ""),
            ("ql10-blocks", env.EXP / "ql10-blocks" / "results" / "results.csv", "tier"))
    for name, p, grp in srcs:
        probs: dict[tuple[str, str], set[str]] = defaultdict(set)
        draws: dict[tuple[str, str], set[str]] = defaultdict(set)
        count: dict[tuple[str, str], int] = defaultdict(int)
        for r in read(p):
            if r.get("outcome") == "not_run":
                continue
            key = (r["arm"], r[grp] if grp and grp in r else "")
            probs[key].add(r["problem"])
            draws[key].add(r.get("draw", "1"))
            count[key] += 1
        for (arm, tier) in sorted(probs):
            out.append({"experiment": name, "arm": arm + (f" ({tier})" if tier else ""),
                        "endpoints": "gates", "problems": len(probs[(arm, tier)]),
                        "draws": len(draws[(arm, tier)]), "result rows": count[(arm, tier)],
                        "k4 / k6": "no replies"})
    return out


def gap_cost() -> list[dict[str, Any]]:
    est = read(env.EXP / "ql10-blocks" / "results" / "a_calls_estimate.csv")
    t_in = sum(int(r["est_tokens_in"]) for r in est)
    t_out = sum(int(r["est_tokens_out"]) for r in est)
    ve = {r["endpoint"] + r["cell"][0]: float(r["cells_total"])
          for r in read(env.RES / "ve_endpoint_size.csv")}
    base = ve["gateO"]
    out = []
    for ep, key in (("gates", "gateO"), ("k4", "k4O"), ("k6", "k6O")):
        ratio = ve[key] / base
        out.append({"endpoint": ep, "arm": "A (whole netlist)", "calls": len(est),
                    "est tokens in": round(t_in * ratio), "est tokens out": t_out,
                    "basis": "gates: Q-L10 a_calls_estimate.csv (estimate: prompt bytes / 3.2); "
                             "k4, k6: gates figure times the cell-count ratio of the 156 "
                             f"VerilogEval designs (ratio {ratio:.2f}); a LUT line carries a "
                             "truth table, so "
                             "this is a rough estimate, not a bound"})
    return out


def summary() -> str:
    r = env.RES
    inv, gap = inventory(), gap_cost()
    write("inventory.csv", inv)
    write("gap_cost.csv", gap)
    parts = ["# Q-L11 results (generated by q11_report.py; no model call)\n",
             "Seeded bootstrap (seed 20261103, 2000 resamples, problems resampled). All LLM arms "
             "exist for the gates endpoint only.\n",
             "## Inventory of model replies\n", md(inv),
             "\n## Scorer comparison (16 problems, arm A draw 1)\n",
             md(read(r / "scorer_compare.csv")),
             "\n## Paired comparison against arm A, gates endpoint\n",
             md(read(r / "paired.csv"),
                ["comparison", "metric", "writer", "problems", "draws", "mean_arm", "mean_ref",
                 "diff", "ci_lo", "ci_hi", "draws_WLT", "problems_WLT", "label"]),
             "\n## Cost of the missing k4 and k6 arms (no call made)\n", md(gap),
             "\n## Endpoint size, benchmark TEST units (Q-L4 to Q-L9)\n",
             md(read(r / "endpoint_size.csv")),
             "\n## Endpoint size, the VerilogEval designs\n", md(read(r / "ve_endpoint_size.csv")),
             "\n## Recovery by kind and endpoint (Q-L9 HEAD, TEST, 1141 constructs)\n",
             md(read(r / "taxonomy_kind_endpoint.csv")),
             "\n## Where the loss sits in the pipeline\n", md(read(r / "loss_stage.csv")),
             "\n## Size test (H-L11)\n", md(read(r / "size_test.csv")),
             "\n## Provenance mixing, descriptive\n", md(read(r / "mixing_desc.csv"))]
    return "\n".join(parts)


def main() -> int:
    (env.RES / "summary.md").write_text(summary(), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
