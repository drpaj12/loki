"""Summary tables of Q-L13 from ``results/*.csv`` (no model call): ``results/summary.md``.

Reads flow.csv, chain.csv, catalogue.csv, gds_blocks.csv, prior_key.csv. Labels per design:
SUPPORTED (LVS match, (a) and (b) both 1.0), CONTRADICTED (LVS match, either below 1.0), OUT (no LVS
match: the flow failed or LVS did not match; outside the hypothesis). Headline first.
"""

from __future__ import annotations

import sys
from collections import Counter
from typing import Any

import ql13_env as env


def label(chain: dict[str, str] | None) -> str:
    if chain is None or chain["lvs"] != "match":
        return "OUT"
    return "SUPPORTED" if chain["a_share"] == "1.0000" and chain["b_reach_share"] == "1.0000" \
        else "CONTRADICTED"


def pct(n: int, d: int) -> str:
    return f"{n / d:.3f}" if d else "n/a"


def main() -> int:
    flow = env.read_csv(env.RES / "flow.csv")
    chain = {r["design"]: r for r in env.read_csv(env.RES / "chain.csv")}
    cat = env.read_csv(env.RES / "catalogue.csv")
    out: list[str] = ["# Q-L13 results (generated by ql13_report.py)", ""]
    lab = {f["design"]: label(chain.get(f["design"])) for f in flow}
    c = Counter(lab.values())
    ok = [d for d, ln in lab.items() if ln != "OUT"]
    out += [f"Designs run: {len(flow)}. LVS match: {len(ok)}. Flow failed or no LVS match: "
            f"{len(flow) - len(ok)}.",
            f"Per-design label (W/L/T style: supported / contradicted / out of scope): "
            f"{c['SUPPORTED']} / {c['CONTRADICTED']} / {c['OUT']}.", ""]
    keys = ("nonfiller", "joined", "logic_denominator", "full_chain", "n_logic", "n_tap", "n_fill",
            "reach_hdl", "n_cts_buffer", "n_repair_buffer", "n_hold_buffer", "n_tie", "n_unjoined",
            "resized", "removed", "odin_cells")
    tot = {k: sum(int(chain[d][k]) for d in ok) for k in keys} if ok else {}
    if ok:
        out += [f"(a) name-free join, LVS-match designs pooled: {tot['joined']} of "
                f"{tot['nonfiller']} non-filler extracted cells = "
                f"{pct(tot['joined'], tot['nonfiller'])}.",
                f"(b) full chain to an HDL line: {tot['full_chain']} of {tot['logic_denominator']} "
                f"logic cells = {pct(tot['full_chain'], tot['logic_denominator'])} with the ir hop "
                f"on the path (strict, v1.4 shape); reaches an HDL span (gates to hdl directly "
                f"or through ir): {tot['reach_hdl']} of {tot['logic_denominator']} = "
                f"{pct(tot['reach_hdl'], tot['logic_denominator'])}. The label uses the second.",
                f"Odin III cells {tot['odin_cells']}; removed by physical design {tot['removed']}; "
                f"resized {tot['resized']}.", ""]
    fails: Counter[tuple[str, str]] = Counter()
    for f in flow:
        if lab[f["design"]] == "OUT":
            key = f["error"].split("] ")[-1] if f["error"].startswith("openroad: [ERROR") \
                else f["error"]
            key = key.replace("openroad: ", "")
            fails[(f["failed_step"], key[:90])] += 1
    out += ["## Designs outside the hypothesis (flow failed or LVS no match)", "",
            "By step and error:", ""]
    out += [f"- {n} x {step}: {err}" for (step, err), n in sorted(fails.items())]
    out += ["", "## Flow, per design", "",
            "| design | exit | s | failed step | error | equiv | LVS | schema_check | disk KB "
            "| label |",
            "|---|---|---|---|---|---|---|---|---|---|"]
    for f in flow:
        out.append("| " + " | ".join([f["design"], f["exit"], f["seconds"], f["failed_step"],
                                      f["error"].replace("|", "/")[:70], f["equiv"], f["lvs"],
                                      f["schema_check"][:20], f["disk_kb"],
                                      lab[f["design"]]])
                   + " |")
    out += ["", "## Chain, per design with a prov directory", "",
            "| design | LVS | extracted | logic | tap | fill | cts | repair | hold | tie "
            "| unjoined | (a) | (b) strict | (b) reach | resized | removed | gds label mismatch |",
            "|" + "---|" * 17]
    for d, r in chain.items():
        out.append("| " + " | ".join([d, r["lvs"], r["extracted"], r["n_logic"], r["n_tap"],
                                      r["n_fill"], r["n_cts_buffer"],
                                      r["n_repair_buffer"], r["n_hold_buffer"], r["n_tie"],
                                      r["n_unjoined"],
                                      r["a_share"], r["b_share"], r["b_reach_share"],
                                      r["resized"], r["removed"],
                                      r["gds_label_mismatch"]]) + " |")
    out += ["", f"## Failure catalogue ({len(cat)} cells)", ""]
    by = Counter((x["broken_at"], x["cause"], x["class"]) for x in cat)
    for (stage, cause, cls), n in sorted(by.items()):
        out.append(f"- {n} x class {cls}: breaks at {stage}: {cause}")
    blocks = {r["design"]: r for r in env.read_csv(env.RES / "gds_blocks.csv")} \
        if (env.RES / "gds_blocks.csv").is_file() else {}
    prior: dict[tuple[str, str], dict[str, Any]] = {
        (r["endpoint"], r["design"]): r for r in env.read_csv(env.RES / "prior_key.csv")}
    out += ["", "## Block recovery without a model: key constructs with a right block", "",
            "Key = flip-flops with the same HDL line and column (no construct type: the chain does "
            "not give one). Each cell: right / key constructs. LVS-match designs first, then the "
            "partial runs (LVS mismatch, descriptive).", "",
            "| design | LVS | gds | gates | lut4 | k4 | k6 |", "|---|---|---|---|---|---|---|"]
    for part in (False, True):
        sums = Counter[str]()
        for d, b in blocks.items():
            if b["status"] != "ok" or (lab.get(d) == "OUT") != part:
                continue
            cells = [d, chain[d]["lvs"], f"{b['key_right']} / {b['key_total']}"]
            sums["gds_t"] += int(b["key_total"])
            sums["gds_r"] += int(b["key_right"])
            for ep in ("gates", "lut4", "k4", "k6"):
                p = prior.get((ep, d))
                cells.append(f"{p['coarse_right']} / {p['coarse_total']}" if p else "")
                if p:
                    sums[ep + "_t"] += int(p["coarse_total"])
                    sums[ep + "_r"] += int(p["coarse_right"])
            seen = int(b["key_total"]) + sum(int(prior[(e, d)]["coarse_total"])
                                             for e in ("gates", "lut4", "k4", "k6")
                                             if (e, d) in prior)
            if seen:
                out.append("| " + " | ".join(str(x) for x in cells) + " |")
        out += ["", ("Partial runs" if part else "LVS-match designs") + " pooled: "
                + ", ".join(f"{ep} {sums[ep + '_r']} of {sums[ep + '_t']} = "
                            f"{pct(sums[ep + '_r'], sums[ep + '_t'])}"
                            for ep in ("gds", "gates", "lut4", "k4", "k6")), ""]
    (env.RES / "summary.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out[:12]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
